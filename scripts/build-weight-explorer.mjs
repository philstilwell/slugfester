// Reproducible projection of the reviewed research set, not a new assessment.
import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import { defaultWeights, weightDimensions, weightTopics, evaluateWeights } from "../src/data/weight-explorer-model.js";
import { DIMENSION_WEIGHTS } from "./lib/reassessment-scoring.mjs";

const root = fileURLToPath(new URL("../", import.meta.url));
const edition = "docs/analysis/corpus-papers-2026-10-09";
const hashes = {};
async function readJson(path) {
  const text = await readFile(root + path, "utf8");
  hashes[path] = createHash("sha256").update(text).digest("hex");
  return JSON.parse(text);
}
const sourceDebates = await readJson(`${edition}/debates.json`);
const sourceMoves = await readJson(`${edition}/moves.json`);
const results = await readJson(`${edition}/results.json`);
assert.deepEqual(defaultWeights, weightDimensions.map(d => DIMENSION_WEIGHTS[d.key] * 100));
const moves = new Map(sourceMoves.map(m => [`${m.number}:${m.move_id}`, m]));
let moveCount = 0;
const debates = [];
for (const d of sourceDebates.filter(d => d.cohort !== "unlocked" && d.theist_side)) {
  const ledger = await readJson(`docs/assessment-ledgers/${d.id}.json`);
  const seen = new Set();
  const sections = ledger.calculated.sections.map(s => {
    const section = { weight: s.weightPercent };
    for (const [label, side] of [["proGod", d.theist_side], ["conGod", d.non_side]]) {
      section[label] = s.sides[side].moves.map(m => {
        const original = moves.get(`${d.number}:${m.moveId}`);
        assert(original, `Missing ${d.number}:${m.moveId}`);
        assert.equal(original.side, side);
        assert.equal(original.importance, m.importance);
        assert.equal(original.score, m.score);
        assert(!seen.has(m.moveId), "Move used more than once");
        seen.add(m.moveId); moveCount++;
        const dimensions = weightDimensions.map(({ key }) => original.dimensions[key]);
        assert(dimensions.every(n => Number.isInteger(n) && n >= 0 && n <= 100));
        assert(m.importance > 0 && Number.isInteger(m.importance));
        assert.equal(Math.round(dimensions.reduce((sum, n, i) => sum + n * (defaultWeights[i] / 100), 0)), m.score);
        return [m.importance, ...dimensions];
      });
      assert(section[label].length > 0);
    }
    return section;
  });
  assert.equal(sections.reduce((n, s) => n + s.weight, 0), 100);
  assert.equal(seen.size, sourceMoves.filter(m => m.number === d.number).length);
  const topic = weightTopics.find(t => t.label === d.topic);
  assert(topic, `Missing reviewed topic for debate ${d.number}`);
  debates.push({ number: d.number, id: d.id, title: d.title, cohort: d.cohort, topic: topic.id,
    speakers: [d.speakers[d.theist_side], d.speakers[d.non_side]],
    published: [d[d.theist_side], d[d.non_side]],
    adjustments: [d.adjustments[d.theist_side], d.adjustments[d.non_side]], sections });
}
const baseline = evaluateWeights(debates);
assert.equal(baseline.count, results.counts.religious);
assert.equal(moveCount, results.counts.religious_moves);
for (const row of baseline.rows) assert.deepEqual([row.proGod, row.conGod], row.published, row.id);
assert(Math.abs(baseline.gap - results.p1.gap.mean) < 1e-12);
const snapshot = { edition: "2026-10-09", date: "October 9, 2026", source: edition, counts: { debates: debates.length, moves: moveCount },
  // Hashes let the check command catch changed inputs rather than silently reuse an old projection.
  sourceHashes: hashes, debates };
const output = `// Generated by scripts/build-weight-explorer.mjs from the reviewed research snapshot.\nexport const weightExplorerSnapshot = ${JSON.stringify(snapshot)};\n`;
const outputPath = root + "src/data/weight-explorer-snapshot.js";
if (process.argv.includes("--check")) assert.equal(await readFile(outputPath, "utf8"), output, "Weight explorer snapshot is stale; rebuild it deliberately.");
else await writeFile(outputPath, output);
console.log(`Weight explorer: ${debates.length} debates, ${moveCount} moves; all default scores match the published results.`);
