export function readerScopeLanguage(text = "") {
  let result = (readerNoteWording.get(text) || text)
    .replaceAll("By explicit editorial approval, this assessment", "This assessment")
    .replaceAll("By explicit editorial approval, ", "")
    .replace(/These AI-generated scores were computed (exactly )?once from a frozen (\d+)-move ledger after two isolated primary judgments and anonymous adjudication of ([^.]+)\./g,
      (_, exactly, count, disagreements) => `Two initial AI reviews were made separately. A further review resolved ${disagreements}, without identifying the original reviewers. The AI-generated scores were calculated ${exactly || ""}once from the finalized record of ${count} selected arguments and replies.`)
    .replace(/\bfrozen (\d+)-move ledger\b/g, "finalized record of $1 selected arguments and replies");
  for (const [before, after] of notePhrases) result = result.replaceAll(before, after);
  return result;
}
